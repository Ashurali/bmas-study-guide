#!/usr/bin/env python3
"""Build docs/reference/glossary.md from every lesson's Key-vocabulary table.

Source: the `## Key vocabulary` table in docs/lessons/*/index.md, with
columns | Term | 中文 | Meaning | (SITE_SPECIFICATION.md §13.1).

Output: one alphabetized table — Term | 中文 | Meaning | Lesson — with each
lesson cell linking to that lesson's vocabulary section. Identical terms are
merged (lessons accumulate); different glosses are kept side by side.

Run after editing a lesson's vocabulary, and in CI before `mkdocs build`.
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "reference" / "glossary.md"

VOCAB_HEADING_RE = re.compile(r"^##\s+(Key vocabulary.*?)\s*$")
CELL_SPLIT_RE = re.compile(r"(?<!\\)\|")  # don't split on escaped \|


def toc_slug(text: str) -> str:
    """Replicate python-markdown's default toc slugify (ASCII-only)."""
    text = unicodedata.normalize("NFKD", text).encode(
        "ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", text)


def sort_key(term: str) -> str:
    """Alphabetize ignoring markdown markup and leading non-alphanumerics."""
    t = re.sub(r"[*`_]", "", term).strip()
    t = re.sub(r"^[^0-9A-Za-z一-鿿]+", "", t)
    return t.casefold()


def parse_front_matter_title(text: str) -> str | None:
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end == -1:
        return None
    m = re.search(r'^title:\s*"?([^"\n]+)"?\s*$', text[4:end], re.M)
    return m.group(1).strip() if m else None


def extract_vocab(text: str) -> tuple[str, list[tuple[str, str, str]]] | None:
    """Return (section_anchor, rows) where rows are (term, zh, meaning)."""
    lines = text.splitlines()
    heading_idx = anchor = None
    for i, line in enumerate(lines):
        m = VOCAB_HEADING_RE.match(line)
        if m:
            heading_idx, anchor = i, toc_slug(m.group(1))
            break
    if heading_idx is None:
        return None

    rows: list[tuple[str, str, str]] = []
    header_seen = False
    for line in lines[heading_idx + 1:]:
        s = line.strip()
        if s.startswith("## "):
            break  # next section
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in CELL_SPLIT_RE.split(s.strip("|"))]
        if len(cells) < 3:
            continue
        if not header_seen:
            header_seen = True  # | Term | 中文 | Meaning |
            continue
        if set(cells[0]) <= {"-", ":", " "}:
            continue  # separator row
        term, zh, meaning = cells[0], cells[1], cells[2]
        if term:
            rows.append((term, zh, meaning))
    return (anchor, rows) if rows else None


def main() -> int:
    entries: dict[str, dict] = {}  # normalized term -> merged entry
    n_lessons = 0

    for path in sorted((DOCS / "lessons").glob("*/index.md")):
        text = path.read_text(encoding="utf-8")
        result = extract_vocab(text)
        if result is None:
            print(f"  WARN: no vocabulary table in {path.parent.name}",
                  file=sys.stderr)
            continue
        anchor, rows = result
        title = parse_front_matter_title(text) or path.parent.name
        lesson_md = f"[{title}](../lessons/{path.parent.name}/index.md#{anchor})"
        n_lessons += 1

        for term, zh, meaning in rows:
            key = sort_key(term)
            e = entries.setdefault(
                key, {"term": term, "zh": [], "meanings": [], "lessons": []})
            if zh and zh not in e["zh"]:
                e["zh"].append(zh)
            if meaning and meaning not in e["meanings"]:
                e["meanings"].append(meaning)
            if lesson_md not in e["lessons"]:
                e["lessons"].append(lesson_md)

    lines = [
        "---",
        'title: "Glossary"',
        "search:",
        "  boost: 2",
        "---",
        "",
        "<!-- AUTO-GENERATED by scripts/build_glossary.py — do not edit by "
        "hand. Re-run the script after editing a lesson's vocabulary. -->",
        "",
        "# Glossary",
        "",
    ]
    if entries:
        lines += [
            f"Every term from the Key-vocabulary tables of {n_lessons} "
            "lesson(s), merged and alphabetized. The lesson link jumps to "
            "where the term is taught.",
            "",
            "| Term | 中文 | Meaning | Lesson |",
            "|---|---|---|---|",
        ]
        for key in sorted(entries):
            e = entries[key]
            zh = "<br>".join(e["zh"])
            meaning = "<br>".join(e["meanings"])
            lessons = " · ".join(e["lessons"])
            lines.append(f"| {e['term']} | {zh} | {meaning} | {lessons} |")
    else:
        lines.append("No lessons built yet — terms appear here as each "
                     "lesson's vocabulary table is written.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(entries)} terms "
          f"from {n_lessons} lesson(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
